-- ============================================================
-- videos: 영상과 분석 상태  [확인]
-- 코드: backend/services/indexer.py (등록·상태 변경·목록), backend/main.py (업로드·즐겨찾기)
-- ============================================================
create table public.videos (
    video_id          uuid primary key default gen_random_uuid(),
    title             text not null,
    video_url         text,
    thumbnail_url     text,
    genre             text,
    duration          double precision,
    status            text not null default 'PENDING',   -- PENDING / PROCESSING / INDEXED / FAILED (코드에서 쓰는 값)
    created_at        timestamptz default now(),
    updated_at        timestamptz default now(),          -- 오래 멈춘 PROCESSING 되돌리기·다운로드 제한 대기에 사용 (아래 트리거 필요)
    youtube_video_id  text,
    storage_path      text,
    subtitle_url      text,
    fps               double precision,
    width             integer,
    height            integer,
    has_audio         boolean,
    error_message     text,
    uploaded_by       uuid,
    source_type       text not null default 'upload',     -- 코드는 'youtube'로 등록 (현재 498행 모두 youtube)
    channel_name      text,
    published_at      timestamptz,
    last_used_at      timestamptz
);

-- [추정] 같은 YouTube 영상이 두 번 등록되지 않게 함. indexer.register_video가 "중복 방지 인덱스"에 걸린 경우를 처리하므로 필요.
--        현재 데이터에 중복·NULL 없음(498행 확인). 업로드 영상(youtube_video_id NULL)은 여러 개 허용.
create unique index if not exists videos_youtube_video_id_key
    on public.videos (youtube_video_id) where youtube_video_id is not null;

-- [추정] list_indexed: status='INDEXED' and source_type='youtube' order by last_used_at desc
create index if not exists videos_status_source_last_used_idx
    on public.videos (status, source_type, last_used_at desc);

-- [추정] updated_at 자동 갱신. indexer.reclaim_stale(30분 넘게 PROCESSING인 영상 되돌리기)와
--        search_api._recently_blocked(다운로드 제한 직후 재시도 막기)가 updated_at을 '상태가 바뀐 시각'으로 씀.
create or replace function public.set_updated_at() returns trigger
language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger videos_set_updated_at
    before update on public.videos
    for each row execute function public.set_updated_at();

-- ============================================================
-- video_features: 영상 feature 파일 위치 (한국어 자막이 없는 영상만)  [확인]
-- 코드: indexer.get_feature (video_id로 최신 1개), run_indexing (delete 후 insert)
-- feature_path는 서버의 파일 경로(레포 기준 상대경로 또는 절대경로). 파일 자체는 DB가 아니라 서버 디스크에 있음
-- ============================================================
create table public.video_features (
    id             bigint generated by default as identity primary key,   -- [추정] identity 방식 (REST에서는 bigint NOT NULL PK만 보임)
    video_id       uuid not null references public.videos (video_id),    -- [추정] on delete 동작은 확인 못함 (기본 NO ACTION으로 둠)
    feature_path   text not null,
    segment_sec    double precision default 2,
    num_segments   integer,
    model_version  text,                                                  -- 'moment-detr-clip' / 'stub'
    created_at     timestamptz default now()
);

-- [추정] get_feature / list_indexed: video_id로 조회, id 내림차순
create index if not exists video_features_video_id_idx on public.video_features (video_id, id desc);

-- ============================================================
-- video_captions: VLM 설명문 생성 상태 (영상당 1행)  [2026-10-17 추가, migrations/20261017_video_captions.sql]
-- 코드: backend/services/captions.py. 설명문·임베딩 파일은 서버 디스크(data/processed/captions/)에 있음
-- CAPTION_SEARCH_ENABLED=0이면 쓰지 않음
-- ============================================================
create table public.video_captions (
    video_id       uuid primary key references public.videos (video_id) on delete cascade,
    status         text not null default 'PENDING'
                   check (status in ('PENDING', 'PROCESSING', 'READY', 'FAILED')),
    caption_model  text,
    embed_model    text,
    batch_size     integer,
    num_frames     integer,
    caption_path   text,
    error_message  text,
    started_at     timestamptz,
    finished_at    timestamptz,
    created_at     timestamptz default now(),
    updated_at     timestamptz default now()
);

create trigger video_captions_set_updated_at
    before update on public.video_captions
    for each row execute function public.set_updated_at();

create index if not exists video_captions_status_idx on public.video_captions (status, updated_at);

